import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { submitLaptopCorrection } from "../../api";
import { ReplicaCorrection } from "./ReplicaCorrection";
import type { LaptopCacheHistoryResponse } from "./types";
vi.mock("../../api", () => ({submitLaptopCorrection:vi.fn()}));
const id = (n:number) => `00000000-0000-4000-8000-${String(n).padStart(12,"0")}`;
const history:LaptopCacheHistoryResponse={schema_version:1,canonical_id:id(1),read_only:true,next_after_version:null,current_state:{importance:3,confidence:0.8,status:"active"},project:{subscription_id:id(2),device_id:id(3),company_id:id(4),owner_instance_id:id(5),project_id:id(6),space_id:id(7),area:"workshop",cursor:2,observed_at:null,initialized:true,read_only:true},versions:[{id:id(8),memory_type:"domain_fact",version:2,author:"owner",authored_at:"2026-10-14T10:00:00Z",updated_at:"2026-10-14T10:00:00Z",tombstone:false,text:"old text",summary:"old summary",digest:"a".repeat(64),unavailable_source_ids:[]}]};
afterEach(()=>{cleanup();vi.mocked(submitLaptopCorrection).mockReset();});
it("requires review and retries the identical queued operation after an uncertain response",async()=>{
  vi.mocked(submitLaptopCorrection).mockRejectedValueOnce(new Error("Disconnected after submission"));
  render(<ReplicaCorrection history={history} version={history.versions[0]} />);
  fireEvent.click(screen.getByText("Propose a correction"));
  fireEvent.change(screen.getByLabelText("Corrected memory text"),{target:{value:"reviewed correction"}});
  expect(screen.getByText("Queue correction proposal")).toBeDisabled();
  fireEvent.click(screen.getByRole("checkbox"));
  fireEvent.click(screen.getByText("Queue correction proposal"));
  await screen.findByRole("alert");
  const [subscription,request]=vi.mocked(submitLaptopCorrection).mock.calls[0];
  expect(subscription).toBe(history.project.subscription_id);
  expect(request.source_memory_id).toBe(history.versions[0].id);
  expect(request.expected_digest).toBe(history.versions[0].digest);
  expect(request.content.canonical_text).toBe("reviewed correction");
  expect(screen.getByLabelText("Corrected memory text")).toBeDisabled();
  vi.mocked(submitLaptopCorrection).mockResolvedValue({operation_id:request.operation_id,subscription_id:subscription,local_memory_id:id(9),local_canonical_id:id(9),owner_canonical_id:history.canonical_id,expected_version:2,request_sha256:"b".repeat(64),staged_at:"2026-10-14T10:01:00Z"});
  fireEvent.click(screen.getByText("Retry same correction"));
  expect(await screen.findByRole("status")).toHaveTextContent("does not mean the owner accepted");
  expect(vi.mocked(submitLaptopCorrection).mock.calls[1][1]).toEqual(request);
});
